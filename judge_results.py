#!/usr/bin/env python3
"""LLM-as-judge validation of gold results produced by executed programs."""

import argparse
import base64
import json
import shutil
import sys
import time
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor, as_completed

from engine.base_engine import LLMEngine
from utils import CostTracker, is_image, encode_image, load_text

MAX_TOTAL_CONTENT_CHARS = 80_000

_cost_tracker: CostTracker = None


def collect_dataset_previews(task_dir: Path):
    previews = []
    for fp in sorted(task_dir.glob("*.txt")):
        if fp.name == "task_instruction.txt":
            continue
        previews.append({"name": fp.name, "data": load_text(fp)})
    return previews


def collect_gold_results(gold_dir: Path):
    infos = []
    for fp in sorted(gold_dir.rglob("*")):
        if fp.is_dir():
            continue
        rel = str(fp.relative_to(gold_dir))
        size = fp.stat().st_size
        info = {"name": rel, "size": size}
        if is_image(fp):
            info["kind"] = "image"
            info["mime"] = "image/png" if fp.suffix.lower() == ".png" else "image/jpeg"
            info["data"] = encode_image(fp)
        else:
            try:
                info["kind"] = "text"
                info["data"] = load_text(fp)
            except UnicodeDecodeError:
                info["kind"] = "binary"
                info["data"] = base64.b64encode(fp.read_bytes()[:4000]).decode("utf-8")
        infos.append(info)
    return infos


JUDGE_SYSTEM = (
    "You are a meticulous evaluator for data-driven discovery workflows. "
    "Each task represents an analysis workflow on a dataset -- such as "
    "statistical analysis, machine learning model training, data visualization, "
    "or computational simulation.\n\n"
    "IMPORTANT: The gold results were generated by automatically synthesized "
    "programs. Complete correctness is NOT guaranteed due to possible errors "
    "in code synthesis, data processing, or the execution environment.\n\n"
    "Evaluation Criteria. For a task to PASS, ALL of the following must hold:\n"
    "1. All requested output files must exist. Read the task instruction to "
    "identify every output file that should be produced. Verify each appears "
    "in the manifest. If any requested file is missing, the task FAILS.\n"
    "2. Each output file must be valid. For every file verify that:\n"
    "   - It is non-empty and contains substantive content (no placeholders, "
    "no 'TODO', no all-zeros).\n"
    "   - It contains no error messages or stack traces.\n"
    "   - Its content aligns with what the task instruction requested.\n"
    "   - Its format and values are reasonable for the analysis type.\n"
    "   Use your domain knowledge to assess whether the results are plausible.\n\n"
    "Evaluation Procedure:\n"
    "1. Identify required output files from the task instruction.\n"
    "2. Check file existence against the manifest.\n"
    "3. Validate each file for correctness, completeness, and plausibility.\n"
    "4. Render a final decision: PASS only if all files exist and all are valid.\n\n"
    "Output Format. Return a JSON object with exactly three fields:\n"
    '{"valid": true|false, "reason": "<explanation>", "confidence": <0.0-1.0>}'
)


def build_messages(task_name, instruction, dataset_previews, gold_infos):
    budget = MAX_TOTAL_CONTENT_CHARS
    preview_budget = budget // 5
    results_budget = budget * 4 // 5

    preview_lines, used = [], 0
    for p in dataset_previews:
        chunk = f"----- Dataset: {p['name']} -----\n{p['data']}\n"
        if used + len(chunk) > preview_budget:
            break
        preview_lines.append(chunk)
        used += len(chunk)
    preview_blob = "\n".join(preview_lines) or "[No dataset preview files]"

    files_list = "\n".join(
        f"  - {i['name']} ({i['kind']}, {i['size']} bytes)" for i in gold_infos
    ) or "  [No files created]"

    text_chunks, content_blocks = [], []
    used = 0
    for info in gold_infos:
        if info["kind"] == "image":
            content_blocks.append({
                "type": "image_url",
                "image_url": {"url": f"data:{info.get('mime','image/png')};base64,{info['data']}"},
            })
            text_chunks.append(f"----- Gold Result: {info['name']} -----\n[Image - see attachment]\n")
        elif info["kind"] == "text":
            chunk = f"----- Gold Result: {info['name']} -----\n{info['data']}\n"
            if used + len(chunk) > results_budget:
                text_chunks.append("\n...[Additional files truncated]...\n")
                break
            text_chunks.append(chunk)
            used += len(chunk)
        else:
            chunk = f"----- Gold Result: {info['name']} (base64) -----\n{info['data']}\n"
            if used + len(chunk) <= results_budget:
                text_chunks.append(chunk)
                used += len(chunk)

    text_blob = "\n".join(text_chunks) or "[No result content to display]"

    user_text = (
        f"# Task: {task_name}\n\n"
        f"## Task Instruction:\n{instruction}\n\n"
        f"## Dataset Previews:\n{preview_blob}\n\n"
        f"## Files Created in pred_results/:\n{files_list}\n\n"
        f"## Content of Each Output File:\n{text_blob}\n\n"
        "---\n\n"
        "Evaluate the task following the procedure in your system prompt. "
        "Return your evaluation as JSON only (valid, reason, confidence)."
    )

    return [
        {"role": "system", "content": JUDGE_SYSTEM},
        {"role": "user", "content": [{"type": "text", "text": user_text}, *content_blocks]},
    ]


def parse_judge_response(raw: str):
    if raw in ("EMPTY_RESPONSE",) or raw.startswith("ERROR:"):
        return False, raw, 0.0
    try:
        payload = raw[raw.index("{"):raw.rindex("}") + 1]
        data = json.loads(payload)
        return bool(data.get("valid")), data.get("reason", ""), float(data.get("confidence", 0))
    except Exception as e:
        return False, f"Unparseable ({e}): {raw[:300]}", 0.0


def evaluate_task(task_dir: Path, engine: LLMEngine) -> dict:
    task_name = task_dir.name
    pred_dir = task_dir / "pred_results"
    result = {"task": task_name, "valid": False, "reason": "", "confidence": 0.0}

    if not pred_dir.exists():
        result["reason"] = "pred_results/ missing"
        return result

    try:
        instruction = (task_dir / "task_instruction.txt").read_text(encoding="utf-8", errors="ignore")
        previews = collect_dataset_previews(task_dir)
        gold_infos = collect_gold_results(pred_dir)
        if not gold_infos:
            result["reason"] = "No result files in pred_results/"
            return result

        messages = build_messages(task_name, instruction, previews, gold_infos)
        raw, ptok, ctok, _ = engine.respond(messages, temperature=0.1, top_p=0.9)
        _cost_tracker.track(ptok, ctok, task_name)

        valid, reason, conf = parse_judge_response(raw or "EMPTY_RESPONSE")
        result.update(valid=valid, reason=reason, confidence=conf)
    except Exception as e:
        result["reason"] = f"Exception: {e}"
    return result


def main():
    parser = argparse.ArgumentParser(description="Judge gold results (Step 2)")
    parser.add_argument("--input-dir", type=str, required=True,
                        help="Directory with executed task_* folders")
    parser.add_argument("--output-dir", type=str, required=True,
                        help="Output directory for validated tasks")
    parser.add_argument("--llm-engine", type=str, default="us.anthropic.claude-sonnet-4-20250514-v1:0",
                        help="LLM engine name")
    parser.add_argument("--litellm-model-name", type=str, default=None,
                        help="LiteLLM model name for cost tracking")
    parser.add_argument("--max-workers", type=int, default=8)
    args = parser.parse_args()

    input_root = Path(args.input_dir).resolve()
    output_root = Path(args.output_dir).resolve()
    output_root.mkdir(parents=True, exist_ok=True)

    global _cost_tracker
    _cost_tracker = CostTracker(
        args.litellm_model_name or args.llm_engine,
        step_name="judge_gold_results",
    )
    engine = LLMEngine(args.llm_engine)

    task_dirs = sorted(
        d for d in input_root.iterdir() if d.is_dir() and d.name.startswith("task_")
    )
    print(f"Found {len(task_dirs)} tasks. Workers: {args.max_workers}")

    start = time.time()
    passed = 0

    with ThreadPoolExecutor(max_workers=args.max_workers) as pool:
        futs = {pool.submit(evaluate_task, td, engine): td for td in task_dirs}
        done = 0
        for fut in as_completed(futs):
            done += 1
            try:
                res = fut.result()
                status = "PASS" if res["valid"] else "FAIL"
                print(f"[{done}/{len(task_dirs)}] {res['task']}: {status} "
                      f"(conf={res['confidence']:.2f}) - {res['reason'][:120]}")
                if res["valid"]:
                    src = futs[fut]
                    dest = output_root / src.name
                    if not dest.exists():
                        shutil.copytree(str(src), str(dest))
                    passed += 1
            except Exception as e:
                print(f"[ERROR] {futs[fut].name}: {e}", file=sys.stderr)

    elapsed = time.time() - start
    print(f"\nDone. Passed: {passed}/{len(task_dirs)} in {elapsed:.1f}s. Output: {output_root}")
    _cost_tracker.save_report(output_root)


if __name__ == "__main__":
    main()
